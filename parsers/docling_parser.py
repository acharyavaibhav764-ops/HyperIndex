"""
parsers/docling_parser.py — DoclingParser for .docx and .pptx files.

Implements the BaseParser interface by wrapping Docling's DocumentConverter
with an in-memory DocumentStream, avoiding any temporary file writes.

Supported extensions: .docx, .pptx

v2 additions
------------
* Picture description (opt-in via ENABLE_PICTURE_DESCRIPTION=true env flag):
  Uses Docling's built-in PictureDescriptionVlmEngineOptions with the
  ``smolvlm`` preset (HuggingFaceTB/SmolVLM-256M-Instruct, ~256MB VRAM,
  runs in-process via Transformers).  Escalation path: ``granite_vision``
  preset (Granite-Vision-3.3-2B via Ollama).

  DeepSeek-OCR2 is intentionally NOT used here — it requires ≥8GB VRAM
  and the development machine has a GTX 1650 (4GB). DeepSeek-OCR2 is
  planned for v5 (PDF branch) on production hardware.
  See parsing_architecture_plan.md for the v6 vLLM migration context.

* Docling issue #1226 workaround: picture descriptions generated by the VLM
  do not appear in export_to_markdown() output or HybridChunker's text stream.
  After conversion, this module injects each description as a CAPTION text
  item directly into the DoclingDocument so it flows through the existing
  chunker path unchanged.

* LibreOffice dependency: plain embedded raster images (standard
  <a:blip r:embed> references) are extracted without LibreOffice — they are
  stored as raw blobs inside the Office zip container.  DrawingML shape-based
  graphics (charts, SmartArt) require LibreOffice on PATH to render; without
  it, text content within those shapes is still recovered but no image is
  extracted.  This is logged as a warning, not an error.

* Crash guard: a known Docling bug causes do_picture_classification /
  do_picture_description to throw on native chart shapes (OLE objects, not
  raster images).  The converter is called with the VLM pipeline first; if it
  raises any exception, it falls back to a plain conversion and logs a warning.
  One bad shape should not take down an entire document's conversion.
"""
import io
import logging

from docling.datamodel.base_models import InputFormat
from docling.document_converter import (
    DocumentConverter,
    WordFormatOption,
    PowerpointFormatOption,
    PdfFormatOption,
)
from docling_core.types.doc import DocItemLabel, DoclingDocument, SectionHeaderItem
from docling_core.types.io import DocumentStream

from config import settings
from .base import BaseParser

logger = logging.getLogger(__name__)


def _build_text_layer_converter() -> DocumentConverter:
    """v5.7: PDF converter that trusts the embedded text layer (no OCR).

    Table structure recognition stays on; only the OCR stage is removed.
    """
    from docling.datamodel.pipeline_options import PdfPipelineOptions

    opts = PdfPipelineOptions(do_ocr=False, do_table_structure=True)
    return DocumentConverter(
        format_options={InputFormat.PDF: PdfFormatOption(pipeline_options=opts)}
    )


def _build_vlm_converter(do_ocr: bool = True) -> DocumentConverter:
    """Build a DocumentConverter with picture description enabled.

    Uses PictureDescriptionVlmEngineOptions.from_preset() with the preset
    specified by ``settings.picture_description_preset``.  Falls back to the
    ``smolvlm`` preset if the configured preset is not registered.

    If ``settings.enable_picture_description`` is False, returns a plain
    ``DocumentConverter()`` immediately so PDF callers (which always call this
    function when on the image tier) also respect the opt-out flag — matching
    the gating already applied in ``DoclingParser.parse()`` for DOCX/PPTX.

    Returns:
        DocumentConverter: Converter with VLM pipeline options applied to
                           DOCX, PPTX, and PDF format options; or a plain
                           DocumentConverter if picture description is disabled.
    """
    from docling.datamodel.pipeline_options import (
        ConvertPipelineOptions,
        PdfPipelineOptions,
        PictureDescriptionVlmEngineOptions,
    )

    # Fix 3: honour the opt-out flag for PDF callers too, matching DoclingParser.parse()
    if not settings.enable_picture_description:
        return DocumentConverter() if do_ocr else _build_text_layer_converter()

    try:
        picture_opts = PictureDescriptionVlmEngineOptions.from_preset(
            settings.picture_description_preset
        )
    except Exception:
        logger.warning(
            "Preset %r not found; falling back to 'smolvlm'.",
            settings.picture_description_preset,
        )
        picture_opts = PictureDescriptionVlmEngineOptions.from_preset("smolvlm")

    # Override prompt from config if provided
    if settings.picture_description_prompt:
        picture_opts = picture_opts.model_copy(
            update={"prompt": settings.picture_description_prompt}
        )

    # DOCX/PPTX use the generic pipeline options class (no PDF-specific fields needed)
    pipeline_options = ConvertPipelineOptions(
        do_picture_classification=True,
        do_picture_description=True,
        picture_description_options=picture_opts,
    )

    # Fix 1: PDF needs PdfPipelineOptions — the PDF-specific subclass that carries
    # generate_page_images, OCR options, and table-structure options.
    # ConvertPipelineOptions (used in v5.1 Fix 4a) has none of those fields, so
    # SmolVLM's page-rasterisation path threw AttributeError on every PDF page,
    # silently falling back to PyMuPDF4LLM — meaning the VLM never actually ran.
    pdf_pipeline_options = PdfPipelineOptions(
        do_ocr=do_ocr,               # v5.7: False for pages that have a text layer
        do_picture_classification=True,
        do_picture_description=True,
        picture_description_options=picture_opts,
        generate_page_images=True,   # required: VLM needs a rasterised page to see
    )

    return DocumentConverter(
        format_options={
            InputFormat.DOCX: WordFormatOption(pipeline_options=pipeline_options),
            InputFormat.PPTX: PowerpointFormatOption(pipeline_options=pipeline_options),
            InputFormat.PDF:  PdfFormatOption(pipeline_options=pdf_pipeline_options),  # v5.2 Fix 1
        }
    )


def _inject_picture_descriptions(doc: DoclingDocument) -> None:
    """Inject picture descriptions from doc.pictures into the text stream.

    Docling stores VLM descriptions in both ``picture.meta.description`` (canonical)
    and ``picture.annotations`` (deprecated). To ensure descriptions with the
    "[Figure description]" prefix and stripped tokens flow through all downstream
    consumers (MarkdownSerializer, HybridChunker, and direct text inspection),
    this function cleans the text and updates:
    1. ``picture.meta.description.text`` (read by MarkdownSerializer / HybridChunker)
    2. ``annotation.text`` (for any consumers still reading annotations)
    3. Adds a CAPTION TextItem to ``doc.texts`` via ``doc.add_text()``.

    Each injected item is tagged with the prefix "[Figure description] " to
    make it distinguishable at retrieval time for future filtering/weighting.

    Args:
        doc: The DoclingDocument returned by DocumentConverter.convert().
             Modified in place — no return value.
    """
    import re
    from docling_core.types.doc import PictureDescriptionData

    for picture in doc.pictures:
        # Determine raw description from either picture.meta.description or annotations
        raw_text = ""
        meta_desc = getattr(getattr(picture, "meta", None), "description", None)
        if meta_desc and getattr(meta_desc, "text", None):
            raw_text = meta_desc.text
        elif getattr(picture, "annotations", None):
            for ann in picture.annotations:
                if isinstance(ann, PictureDescriptionData) and getattr(ann, "text", None):
                    raw_text = ann.text
                    break

        if not raw_text:
            continue

        # Strip complete tokens like <end_of_utterance>
        cleaned = re.sub(r"<[a-z_]{1,40}>", "", raw_text)
        # Strip dangling/unclosed token at end of string (e.g. <end_of_utteranc)
        cleaned = re.sub(r"<[a-z_]{0,40}\s*$", "", cleaned).strip()
        if not cleaned:
            continue

        tagged_description = f"[Figure description] {cleaned}"

        # 1. Update canonical picture.meta.description so HybridChunker picks it up
        if meta_desc is not None:
            meta_desc.text = tagged_description

        # 2. Update deprecated picture.annotations
        if getattr(picture, "annotations", None):
            for ann in picture.annotations:
                if isinstance(ann, PictureDescriptionData):
                    ann.text = tagged_description

        # 3. Inject CAPTION TextItem into doc
        try:
            doc.add_text(
                label=DocItemLabel.CAPTION,
                text=tagged_description,
                parent=picture,
            )
        except Exception as exc:
            logger.warning(
                f"Picture description failed for {picture.self_ref}: {exc}"
            )


def _promote_pptx_pseudo_headings(doc: DoclingDocument) -> None:
    """Identify and promote plain text pseudo-headings on PPTX slides.
    
    Docling's MsPowerpointDocumentBackend often misclassifies text box titles as
    PARAGRAPH. If a PARAGRAPH is short (<100 chars), does not end in a period,
    and is the first textual item on its page, we safely replace the TextItem
    node with a SectionHeaderItem so HybridChunker respects it as a hard boundary.
    """
    page_first_items = {}
    for item in doc.texts:
        if getattr(item, "prov", None):
            p_no = item.prov[0].page_no
            if p_no not in page_first_items:
                page_first_items[p_no] = item
                
    for i, item in enumerate(doc.texts):
        p_no = item.prov[0].page_no if getattr(item, "prov", None) else None
        if p_no and page_first_items.get(p_no) is item:
            if item.label == DocItemLabel.PARAGRAPH:
                text = getattr(item, "text", "").strip()
                if text and len(text) < 100 and not text.endswith("."):
                    dump = item.model_dump()
                    dump["label"] = DocItemLabel.SECTION_HEADER
                    new_item = SectionHeaderItem(**dump)
                    doc.texts[i] = new_item


class DoclingParser(BaseParser):
    """
    Parse Microsoft Office documents (Word and PowerPoint) into a
    :class:`~docling_core.types.doc.DoclingDocument`.

    Files are converted entirely in-memory via a :class:`DocumentStream`,
    so no temporary files are written to disk. Docling's ``DocumentConverter``
    preserves heading hierarchy, tables, and slide text from the native
    Office XML formats.

    When ``settings.enable_picture_description`` is ``True``, the parser
    additionally generates natural-language descriptions for embedded images
    using a local lightweight VLM (SmolVLM-256M by default) and injects those
    descriptions into the document's text stream so they are embedded alongside
    the surrounding text content.

    Supported file types:
        - ``.docx`` — Microsoft Word (Open XML)
        - ``.pptx`` — Microsoft PowerPoint (Open XML)

    Attributes:
        SUPPORTED_EXTENSIONS: Frozenset of lowercase dot-prefixed extensions.
    """

    SUPPORTED_EXTENSIONS: frozenset[str] = frozenset({".docx", ".pptx"})

    def __init__(self) -> None:
        """Instantiate shared DocumentConverter(s) for Office formats.

        Both converters are created lazily on first use:
        - ``_converter``: plain text/table extraction.
        - ``_converter_vlm``: text + picture description via local VLM,
          built only when ``settings.enable_picture_description`` is True.
        """
        self._converter: DocumentConverter | None = None
        self._converter_vlm: DocumentConverter | None = None

    # ------------------------------------------------------------------
    # BaseParser interface
    # ------------------------------------------------------------------

    def can_handle(self, ext: str) -> bool:
        """Return True for .docx and .pptx extensions.

        Args:
            ext: Lowercase, dot-prefixed extension, e.g. ``'.docx'``.
        """
        return ext.lower() in self.SUPPORTED_EXTENSIONS

    def parse(self, file_bytes: bytes, filename: str, **kwargs) -> DoclingDocument:
        """Convert raw Office file bytes to a DoclingDocument.

        The bytes are wrapped in an in-memory :class:`DocumentStream`
        (no temporary files). Docling extracts headings, paragraphs,
        tables, and slide text into a unified ``DoclingDocument``.

        When ``settings.enable_picture_description`` is ``True``:
        - The VLM-enabled converter is used first (with a crash-guard
          fallback to the plain converter on any exception).
        - Picture descriptions are injected into the document's text stream
          via :func:`_inject_picture_descriptions` so they reach the chunker.

        Args:
            file_bytes: Raw binary content of the file.
            filename:   Original filename; used to detect format and set
                        the document origin name.
            **kwargs:   Unused; reserved for future parser options.

        Returns:
            DoclingDocument: Structured representation of the document.
        """
        stream = DocumentStream(name=filename, stream=io.BytesIO(file_bytes))

        if settings.enable_picture_description:
            doc = self._convert_with_vlm(stream, filename)
        else:
            if self._converter is None:
                self._converter = DocumentConverter()
            result = self._converter.convert(stream)
            doc = result.document

        if filename.lower().endswith(".pptx"):
            _promote_pptx_pseudo_headings(doc)

        return doc

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    def _convert_with_vlm(
        self, stream: DocumentStream, filename: str
    ) -> DoclingDocument:
        """Run conversion with VLM picture description, falling back on error.

        Crash guard: a known Docling bug causes do_picture_classification /
        do_picture_description to throw on native chart shapes (OLE objects,
        not raster images).  One bad shape should not take down an entire
        file's conversion.

        Args:
            stream:   In-memory :class:`DocumentStream` for the file.
            filename: Original filename for log messages.

        Returns:
            DoclingDocument: Parsed document, with picture descriptions
                             injected when VLM conversion succeeded.
        """
        # Lazy-init the VLM converter — only built if picture description is enabled
        if self._converter_vlm is None:
            try:
                self._converter_vlm = _build_vlm_converter()
            except Exception as exc:
                logger.warning(
                    "Failed to build VLM converter for %s: %s. "
                    "Falling back to plain conversion.",
                    filename,
                    exc,
                )
                if self._converter is None:
                    self._converter = DocumentConverter()
                result = self._converter.convert(stream)
                return result.document

        try:
            result = self._converter_vlm.convert(stream)
            doc = result.document
            # Inject VLM descriptions into the text stream (Docling issue #1226)
            _inject_picture_descriptions(doc)
            return doc
        except Exception as exc:
            logger.warning(
                "VLM conversion failed for %s: %s. Retrying without picture description.",
                filename,
                exc,
            )
            # Re-wrap bytes for the fallback (the stream may already be exhausted)
            fallback_stream = DocumentStream(
                name=filename, stream=io.BytesIO(stream.stream.getvalue())
            )
            if self._converter is None:
                self._converter = DocumentConverter()
            result = self._converter.convert(fallback_stream)
            return result.document
